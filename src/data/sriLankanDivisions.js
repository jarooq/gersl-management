export const getAllDistricts = () => {
  return Object.keys(SRI_LANKAN_ADMINISTRATIVE_DIVISIONS).sort();
};

export const getDSDivisionsByDistrict = (district) => {
  const districtData = SRI_LANKAN_ADMINISTRATIVE_DIVISIONS[district];
  return districtData ? Object.keys(districtData).sort() : [];
};

export const getGNDivisionsByDSDivision = (district, dsDivision) => {
  const districtData = SRI_LANKAN_ADMINISTRATIVE_DIVISIONS[district];
  if (!districtData) return [];
  return districtData[dsDivision] || [];
};
