// PDF export for fuel claims. Streams a single-page summary suitable for
// approval/audit: staff name, period, route, distance, lunch deduction, rate
// per km, claim amount, approval state. Uses pdfkit (no headless browser
// required, lightweight, deterministic layout).

import PDFDocument from 'pdfkit';
import asyncHandler from 'express-async-handler';
import { FuelClaim, FuelRate, MovementLog, User, Vehicle } from '../models/index.js';

export const renderFuelClaimPdf = asyncHandler(async (req, res) => {
  const claim = await FuelClaim.findByPk(req.params.id, {
    include: [
      { model: User,        as: 'staff',    attributes: ['id', 'fullName', 'email', 'role'] },
      { model: User,        as: 'approver', attributes: ['id', 'fullName'] },
      { model: MovementLog, as: 'movement' },
      { model: Vehicle,     as: 'vehicle' },
      { model: FuelRate,    as: 'fuelRate' }
    ]
  });
  if (!claim) return res.status(404).json({ success: false, message: 'not found' });

  // Authz — owner or approver roles only.
  const allowed = ['Admin', 'CEO', 'Director Programmes', 'Programme Manager',
                   'HR Manager', 'Finance Manager', 'Procurement Manager'];
  if (claim.userId !== req.user.id && !allowed.includes(req.user.role)) {
    return res.status(403).json({ success: false, message: 'forbidden' });
  }

  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `inline; filename="fuel-claim-${claim.id}.pdf"`);

  const doc = new PDFDocument({ size: 'A4', margin: 48 });
  doc.pipe(res);

  // Header
  doc.fontSize(18).text('Fuel claim verification', { align: 'left' });
  doc.fontSize(10).fillColor('#666').text(`Claim #${claim.id} · ${new Date().toLocaleDateString()}`);
  doc.moveDown();
  doc.fillColor('#000');

  // Staff
  doc.fontSize(12).text(`Staff: ${claim.staff?.fullName ?? '—'}`);
  if (claim.staff?.role) doc.text(`Role:  ${claim.staff.role}`);
  doc.moveDown(0.5);

  // Movement
  const mv = claim.movement;
  if (mv) {
    doc.text(`Route: ${mv.fromLocation ?? '—'} → ${mv.toLocation ?? '—'}`);
    doc.text(`Purpose: ${mv.purpose ?? '—'}`);
    if (mv.departureAt) doc.text(`Departed: ${new Date(mv.departureAt).toLocaleString()}`);
    if (mv.returnAt)    doc.text(`Returned: ${new Date(mv.returnAt).toLocaleString()}`);
  }
  doc.moveDown(0.5);

  // Vehicle
  if (claim.vehicle) {
    doc.text(`Vehicle: ${claim.vehicle.label ?? claim.vehicle.plateNo ?? '—'} (${claim.vehicle.vehicleType ?? '—'})`);
  }
  doc.moveDown(0.5);

  // Calculation
  doc.fontSize(13).text('Calculation', { underline: true });
  doc.fontSize(11);
  doc.text(`Distance:           ${claim.distanceKm ?? '—'} km`);
  if (claim.lunchDeductionKm) doc.text(`Lunch deduction:    -${claim.lunchDeductionKm} km`);
  doc.text(`Eligible distance:  ${claim.eligibleKm ?? claim.distanceKm ?? '—'} km`);
  doc.text(`Rate:               Rs ${claim.ratePerKm ?? claim.fuelRate?.ratePerKm ?? '—'}/km`);
  doc.font('Helvetica-Bold').text(`Claim amount:       Rs ${claim.claimAmount ?? '—'}`);
  doc.font('Helvetica');
  doc.moveDown();

  // Approval
  doc.fontSize(13).text('Approval', { underline: true });
  doc.fontSize(11);
  doc.text(`Status:    ${claim.status ?? 'Pending'}`);
  if (claim.approver?.fullName)  doc.text(`Approved by: ${claim.approver.fullName}`);
  if (claim.approvedAt)          doc.text(`Approved at: ${new Date(claim.approvedAt).toLocaleString()}`);
  if (claim.rejectionReason)     doc.text(`Rejection reason: ${claim.rejectionReason}`);

  doc.moveDown(2);
  doc.fontSize(8).fillColor('#888')
     .text('Generated by GERSL field-staff system. Distance and timestamps are derived from GPS data captured by the staff mobile app.', { align: 'left' });

  doc.end();
});
